const sample = `{"releases": [
  {"date": "2026-11-02", "status": "previous"},
  {"date": "2026-11-09", "status": "withdrawn"},
  {"date": "2026-11-16", "status": "current"},
  {"date": "2026-11-23", "status": "current"}
]}`

func TestParseReleases(t *testing.T) {
	r, err := ParseReleases([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	if len(r.Releases) != 4 || r.Releases[3] != (Release{"2026-11-23", Current}) {
		t.Errorf("got %+v", r.Releases)
	}
	for name, bad := range map[string]string{
		"not json":       `{`,
		"bad date":       `{"releases": [{"date": "2026-13-01", "status": "current"}]}`,
		"short date":     `{"releases": [{"date": "2026-1-01", "status": "current"}]}`,
		"twice":          `{"releases": [{"date": "2026-11-16", "status": "current"}, {"date": "2026-11-16", "status": "previous"}]}`,
		"unknown status": `{"releases": [{"date": "2026-11-16", "status": "beta"}]}`,
		"unknown field":  `{"releases": [], "latest": "2026-11-16"}`,
	} {
		if _, err := ParseReleases([]byte(bad)); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}
}

func TestChoose(t *testing.T) {
	r, err := ParseReleases([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		running, want, got, err string
	}{
		{running: "2026-11-02", got: "2026-11-23"},                     // newest current, not just the first
		{running: "2026-11-16", want: "2026-11-16", got: "2026-11-16"}, // the running date again is allowed
		{running: "2026-11-02", want: "2026-11-16", got: "2026-11-16"},
		{running: "2026-11-02", want: "2026-11-02", got: "2026-11-02"}, // previous, not withdrawn
		{running: "2026-11-02", want: "2026-11-09", err: "withdrawn"},
		{running: "2026-11-02", want: "2026-11-10", err: "not a rollgate release"},
		{running: "2026-11-02", want: "next week", err: "not a date"},
		{running: "2026-11-16", want: "2026-11-02", err: "rollgate rollback"},
	} {
		got, err := r.Choose(tc.running, tc.want)
		switch {
		case tc.err != "" && (err == nil || !strings.Contains(err.Error(), tc.err)):
			t.Errorf("Choose(%s, %q): err %v, want %q", tc.running, tc.want, err, tc.err)
		case tc.err == "" && (err != nil || got != tc.got):
			t.Errorf("Choose(%s, %q) = %s, %v; want %s", tc.running, tc.want, got, err, tc.got)
		}
	}
	if _, err := r.Choose("2026-11-23", ""); !errors.Is(err, ErrUpToDate) {
		t.Errorf("newest already running: %v, want ErrUpToDate", err)
	}
	none := Releases{Releases: []Release{{"2026-11-02", Previous}}}
	if _, err := none.Choose("2026-11-02", ""); err == nil {
		t.Error("no current release: accepted")
	}
}

func TestRunningRelease(t *testing.T) {
	for _, tc := range []struct{ list, want, err string }{
		{list: "# Generated by image/build.sh. Pinned to release 2026-11-16 (ADR 0002).\nServer = https://archive.archlinux.org/repos/2026/11/16/$repo/os/$arch\n", want: "2026-11-16"},
		{list: "Server = https://archive.archlinux.org/repos/2026/11/16/$repo/os/$arch\nServer = https://archive.archlinux.org/repos/2026/11/16/$repo/os/$arch\n", want: "2026-11-16"},
		{list: "Server = https://archive.archlinux.org/repos/2026/11/16/$repo/os/$arch\nServer = https://archive.archlinux.org/repos/2026/11/23/$repo/os/$arch\n", err: "two dates"},
		{list: "Server = https://geo.mirror.pkgbuild.com/$repo/os/$arch\n", err: "no Arch Linux Archive date"},
		{list: "#Server = https://archive.archlinux.org/repos/2026/11/16/$repo/os/$arch\n", err: "no Arch Linux Archive date"},
		{list: "Server = https://archive.archlinux.org/repos/2026/02/30/$repo/os/$arch\n", err: "no Arch Linux Archive date"},
	} {
		root := t.TempDir()
		path := filepath.Join(root, MirrorlistPath)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(tc.list), 0o644); err != nil {
			t.Fatal(err)
		}
		got, err := RunningRelease(root)
		switch {
		case tc.err != "" && (err == nil || !strings.Contains(err.Error(), tc.err)):
			t.Errorf("%q: err %v, want %q", tc.list, err, tc.err)
		case tc.err == "" && (err != nil || got != tc.want):
			t.Errorf("%q: got %s, %v; want %s", tc.list, got, err, tc.want)
		}
	}
	if _, err := RunningRelease(t.TempDir()); err == nil {
		t.Error("missing mirrorlist: no error")
	}
}
