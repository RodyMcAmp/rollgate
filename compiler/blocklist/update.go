const (
	// MaxBytes bounds one downloaded list.
	MaxBytes = 32 << 20
	// MaxNames bounds the names Unbound holds, to keep its memory well
	// inside the 2 GB minimum.
	MaxNames = 500_000
	// StatePath (below the root) says what the last update did.
	StatePath = "var/lib/rollgate/dns-blocklist.json"
	// cacheDir (below the root) keeps each list's last good download.
	cacheDir = "var/lib/rollgate/blocklists"
)

// State is what the last update did, for rollgate status and the web UI.
type State struct {
	Updated time.Time `json:"updated"`
	Names   int       `json:"names"`
	Capped  bool      `json:"capped,omitempty"`
	Lists   []List    `json:"lists"`
}

// List is how one entry in dns.blocklists went.
type List struct {
	Entry string `json:"entry"`
	Names int    `json:"names"`
	Error string `json:"error,omitempty"` // the download failed; the last good copy was used, if any
}

// System is the router as the update needs it.
type System struct {
	Root string
	Run  apply.Runner
	Get  func(ctx context.Context, url string) (io.ReadCloser, error)
	Now  func() time.Time
	Out  io.Writer
}

// HTTPGet downloads url over HTTPS, refusing anything but a 200 answer.
func HTTPGet(ctx context.Context, url string) (io.ReadCloser, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "rollgate (+https://github.com/RodyMcAmp/rollgate)")
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("%s answered %s", url, resp.Status)
	}
	return resp.Body, nil
}

func (s System) path(p string) string { return filepath.Join(s.Root, filepath.FromSlash(p)) }

// effectiveConfig is the config the router runs now: the change waiting for
// confirmation if there is one (its unbound.conf is installed), else the
// confirmed one. nil before the first apply.
func effectiveConfig(root string) (*config.Config, error) {
	st := apply.Store{Root: root}
	n, ok, err := st.Pending()
	if err == nil && !ok {
		n, ok, err = st.Current()
	}
	if err != nil || !ok {
		return nil, err
	}
	g, err := st.Load(n)
	if err != nil {
		return nil, err
	}
	return config.Parse(g.Source)
}

// Update is rollgate dns update.
func Update(s System) error {
	c, err := effectiveConfig(s.Root)
	if err != nil {
		return err
	}
	file := s.path(strings.TrimPrefix(compile.BlocklistFile, "/"))
	if c == nil || len(c.DNS.Blocklists) == 0 {
		// Nothing to block: unbound.conf doesn't include the file, so it only
		// takes space. If there was one, dnsmasq may still have blocked
		// answers cached.
		had := os.Remove(file) == nil
		_ = os.RemoveAll(s.path(cacheDir))
		_ = os.Remove(s.path(StatePath))
		if had {
			s.flushDNSCache()
		}
		fmt.Fprintln(s.Out, "No DNS blocklists are set (dns.blocklists); nothing to block.")
		return nil
	}

	st := State{Updated: s.Now().UTC()}
	var lists [][]string
	for _, entry := range c.DNS.Blocklists {
		names, err := s.fetch(entry)
		l := List{Entry: entry, Names: len(names)}
		if err != nil {
			l.Error = err.Error()
			fmt.Fprintf(s.Out, "%s: %v\n", entry, err)
		}
		st.Lists = append(st.Lists, l)
		lists = append(lists, names)
	}
	keep := func(n string) bool {
		for _, z := range []string{c.System.Domain, "localhost"} {
			if z != "" && under(n, z) {
				return true
			}
		}
		return n == strings.ToLower(c.System.Hostname)
	}
	names, capped := Build(lists, c.DNS.Allow, keep, MaxNames)
	st.Names, st.Capped = len(names), capped
	if capped {
		fmt.Fprintf(s.Out, "warning: the lists have more than %d names; only the first %d are used\n", MaxNames, MaxNames)
	}
	if len(names) == 0 {
		// Every download failed and nothing was cached: keep what Unbound has.
		_ = s.saveState(st)
		return errors.New("no list could be downloaded and none was saved before; Unbound keeps what it had")
	}
	header := fmt.Sprintf("# Generated by rollgate dns update (ADR 0019) on %s from dns.blocklists.\n# Don't edit: the next update replaces it.\n",
		st.Updated.Format("2006-01-02 15:04 UTC"))
	if err := s.install(file, Render(names, c.DNS.Allow, header)); err != nil {
		_ = s.saveState(st)
		return err
	}
	fmt.Fprintf(s.Out, "Blocking %d names from %d list(s).\n", len(names), len(c.DNS.Blocklists))
	return s.saveState(st)
}

// fetch downloads one list and parses it. On success it saves the names as
// the list's last good copy; on failure it returns that copy, if any, with
// the error.
func (s System) fetch(entry string) ([]string, error) {
	url := config.BlocklistURL(entry)
	sum := sha256.Sum256([]byte(url))
	cache := filepath.Join(s.path(cacheDir), hex.EncodeToString(sum[:8])+".txt")
	names, err := s.download(url)
	if err == nil {
		if mkErr := os.MkdirAll(filepath.Dir(cache), 0o755); mkErr == nil {
			_ = writeAtomic(cache, []byte(strings.Join(names, "\n")+"\n"))
		}
		return names, nil
	}
	if old, rerr := os.ReadFile(cache); rerr == nil {
		cached, _ := Parse(bytes.NewReader(old))
		return cached, fmt.Errorf("%w; using the copy from the last good download", err)
	}
	return nil, err
}

func (s System) download(url string) ([]string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()
	body, err := s.Get(ctx, url)
	if err != nil {
		return nil, err
	}
	defer body.Close()
	data, err := io.ReadAll(io.LimitReader(body, MaxBytes+1))
	if err != nil {
		return nil, err
	}
	if len(data) > MaxBytes {
		return nil, fmt.Errorf("%s is bigger than %d MB", url, MaxBytes>>20)
	}
	names, err := Parse(bytes.NewReader(data))
	if err == nil && len(names) == 0 {
		err = fmt.Errorf("%s has no names in a format rollgate reads", url)
	}
	return names, err
}

// install puts content in place of file: checked by unbound-checkconf first,
// then Unbound reloads it. If the reload fails, the old file goes back.
func (s System) install(file string, content []byte) error {
	next := file + ".new"
	if err := writeAtomic(next, content); err != nil {
		return err
	}
	defer os.Remove(next)
	dir, err := os.MkdirTemp("", "rollgate-blocklist")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	check := filepath.Join(dir, "check.conf")
	if err := os.WriteFile(check, []byte("include: \""+next+"\"\n"), 0o644); err != nil {
		return err
	}
	if out, err := s.Run.Run("unbound-checkconf", check); err != nil {
		return fmt.Errorf("the new list didn't pass unbound-checkconf, so the old one stays: %v: %s", err, bytes.TrimSpace(out))
	}
	old, oldErr := os.ReadFile(file)
	if err := os.Rename(next, file); err != nil {
		return err
	}
	out, err := s.Run.Run("systemctl", "reload-or-restart", "unbound.service")
	if err == nil {
		s.flushDNSCache()
		return nil
	}
	if oldErr == nil {
		_ = writeAtomic(file, old)
	} else {
		_ = os.Remove(file)
	}
	_, _ = s.Run.Run("systemctl", "reload-or-restart", "unbound.service")
	return fmt.Errorf("unbound didn't take the new list, so the old one is back: %v: %s", err, bytes.TrimSpace(out))
}

// flushDNSCache makes dnsmasq forget its cached answers (SIGHUP), so a name
// that is blocked or allowed now isn't answered from before for up to an hour.
func (s System) flushDNSCache() {
	if out, err := s.Run.Run("systemctl", "kill", "--signal=HUP", "dnsmasq.service"); err != nil {
		fmt.Fprintf(s.Out, "note: couldn't clear dnsmasq's cache (%v: %s); old answers expire within an hour.\n", err, bytes.TrimSpace(out))
	}
}

func (s System) saveState(st State) error {
	b, err := json.MarshalIndent(st, "", "  ")
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(s.path(StatePath)), 0o755); err != nil {
		return err
	}
	return writeAtomic(s.path(StatePath), append(b, '\n'))
}

// ReadState returns what the last update did; ok is false if none ran.
func ReadState(root string) (State, bool) {
	var st State
	b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(StatePath)))
	if err != nil {
		return st, false
	}
	return st, json.Unmarshal(b, &st) == nil
}

// Summary is the line rollgate status shows.
func (st State) Summary() string {
	failed := 0
	for _, l := range st.Lists {
		if l.Error != "" {
			failed++
		}
	}
	s := fmt.Sprintf("DNS blocklists: %d names blocked, updated %s.", st.Names, st.Updated.Format("2006-01-02 15:04 UTC"))
	if failed > 0 {
		s += fmt.Sprintf(" %d of %d list(s) failed to download (journalctl -u rollgate-blocklists).", failed, len(st.Lists))
	}
	return s
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
