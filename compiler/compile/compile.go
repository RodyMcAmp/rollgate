// Package compile turns a validated config into system config files.
//
// Compile is a pure function: config in, files out, no side effects
// (ADR 0005). Every file comes from a template in compiler/templates/ and
// starts with a header naming the generator and the source config.
package compile

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"text/template"

	"github.com/RodyMcAmp/rollgate/compiler/config"
	"github.com/RodyMcAmp/rollgate/compiler/templates"
)

// Files maps a path relative to the filesystem root (e.g.
// "etc/sysctl.d/90-rollgate.conf") to the file's content.
type Files map[string][]byte

var tmpl = template.Must(template.New("").Funcs(funcs).Option("missingkey=error").ParseFS(templates.FS, "*.tmpl"))

// network is the template data for one interface or VLAN.
type network struct {
	Header     string
	Kind       string // "interface" or "VLAN"
	Name       string
	Zone       string
	Device     string // Linux device name, see config.Interface.Device
	MAC        string // interfaces matched by MAC only
	Parent     string // VLANs only
	VLANID     int    // VLANs only
	WAN        bool
	DHCPClient bool
	Addr       string   // router address with prefix, when static
	VLANs      []string // devices of VLANs on this interface
	IPv6Off    bool
}

// Compile renders every file for c. source is the router.toml it was loaded
// from; its name and hash go into each file's header.
func Compile(c *config.Config, source []byte, sourceName string) (Files, error) {
	header := fmt.Sprintf("# Generated by rollgate compile from %s (sha256 %x).\n"+
		"# Do not edit: change router.toml instead (docs/architecture.md#config-flow).",
		sourceName, sha256.Sum256(source))
	ipv6Off := c.System.IPv6 == "off"

	files := Files{}
	add := func(path, name string, data any) error {
		var b bytes.Buffer
		if err := tmpl.ExecuteTemplate(&b, name, data); err != nil {
			return fmt.Errorf("rendering %s: %w", path, err)
		}
		files[path] = b.Bytes()
		return nil
	}

	vlansOn := map[string][]string{}
	for _, v := range c.VLANs {
		vlansOn[v.Parent] = append(vlansOn[v.Parent], v.Name)
	}

	for _, in := range c.Interfaces {
		n := network{
			Header: header, Kind: "interface", Name: in.Name, Zone: in.Zone,
			Device: in.Device(), WAN: in.Zone == "wan", DHCPClient: in.IPv4 == "dhcp",
			VLANs: vlansOn[in.Name], IPv6Off: ipv6Off,
		}
		if in.Addr.IsValid() {
			n.Addr = in.Addr.String()
		}
		if in.MatchMAC != "" {
			n.MAC = in.MatchMAC
			if err := add("etc/systemd/network/10-rollgate-"+in.Name+".link", "link.tmpl", n); err != nil {
				return nil, err
			}
		}
		if err := add("etc/systemd/network/30-rollgate-"+in.Name+".network", "network.tmpl", n); err != nil {
			return nil, err
		}
	}

	for _, v := range c.VLANs {
		n := network{
			Header: header, Kind: "VLAN", Name: v.Name, Zone: v.Zone, Device: v.Name,
			Parent: v.Parent, VLANID: v.ID, WAN: v.Zone == "wan", DHCPClient: v.IPv4 == "dhcp",
			IPv6Off: ipv6Off,
		}
		if v.Addr.IsValid() {
			n.Addr = v.Addr.String()
		}
		if err := add("etc/systemd/network/20-rollgate-"+v.Name+".netdev", "netdev.tmpl", n); err != nil {
			return nil, err
		}
		if err := add("etc/systemd/network/30-rollgate-"+v.Name+".network", "network.tmpl", n); err != nil {
			return nil, err
		}
	}

	sysctl := struct {
		Header  string
		IPv6Off bool
	}{header, ipv6Off}
	if err := add("etc/sysctl.d/90-rollgate.conf", "sysctl.tmpl", sysctl); err != nil {
		return nil, err
	}

	fw, err := buildFirewall(c, header)
	if err != nil {
		return nil, err
	}
	if err := add("etc/nftables.conf", "nftables.tmpl", fw); err != nil {
		return nil, err
	}
	return files, nil
}

// Paths returns the file paths in sorted order.
func (f Files) Paths() []string {
	return slices.Sorted(maps.Keys(f))
}

// WriteTree writes the files below dir, which must not exist yet or be empty,
// so a compile never mixes with older output.
func (f Files) WriteTree(dir string) error {
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		return fmt.Errorf("%s is not empty; choose a new directory", dir)
	}
	for _, p := range f.Paths() {
		target := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, f[p], 0o644); err != nil {
			return err
		}
	}
	return nil
}
