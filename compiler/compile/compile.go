// Package compile turns a validated config into system config files.
//
// Compile is a pure function: config in, files out, no side effects
// (ADR 0005). Every file comes from a template in compiler/templates/ and
// starts with a header naming the generator and the source config.
package compile

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"text/template"

	"github.com/RodyMcAmp/rollgate/compiler/config"
	"github.com/RodyMcAmp/rollgate/compiler/templates"
	"github.com/RodyMcAmp/rollgate/compiler/vpn"
)

// Files maps a path relative to the filesystem root (e.g.
// "etc/sysctl.d/90-rollgate.conf") to the file's content.
type Files map[string][]byte

// generatedPrefix starts every file Compile writes.
const generatedPrefix = "# Generated by rollgate compile from "

// IsGenerated reports whether data is a file Compile wrote, as opposed to,
// say, a distribution's default config.
func IsGenerated(data []byte) bool { return bytes.HasPrefix(data, []byte(generatedPrefix)) }

var tmpl = template.Must(template.New("").Funcs(funcs).Option("missingkey=error").ParseFS(templates.FS, "*.tmpl"))

// network is the template data for one interface or VLAN.
type network struct {
	Header     string
	Kind       string // "interface" or "VLAN"
	Name       string
	Zone       string
	Device     string // Linux device name, see config.Interface.Device
	MAC        string // interfaces matched by MAC only
	Parent     string // VLANs only
	VLANID     int    // VLANs only
	WAN        bool
	DHCPClient bool
	Addr       string   // router address with prefix, when static
	VLANs      []string // devices of VLANs on this interface
	IPv6Off    bool
	IPv6       *lanIPv6 // ipv6 = "auto": non-WAN networks with a static address
	WANIPv6    int      // ipv6 = "auto", WAN only: delegated prefix size to ask for
}

// lanIPv6 is a local network's IPv6 setup (docs/config-spec.md, "How ipv6 =
// auto is compiled").
type lanIPv6 struct {
	Addr     string // router's ULA address with /64
	Prefix   string // the ULA /64 announced to clients
	DNS      string // router's ULA address, announced as DNS server
	SubnetID string // for the ISP's delegated prefix, e.g. "0x4f"
	Domain   string
	Uplink   string // WAN device that receives the delegated prefix
}

// Compile renders every file for c. source is the router.toml it was loaded
// from; its name and hash go into each file's header.
func Compile(c *config.Config, source []byte, sourceName string) (Files, error) {
	header := fmt.Sprintf(generatedPrefix+"%s (sha256 %x).\n"+
		"# Do not edit: change router.toml instead (docs/architecture.md#config-flow).",
		sourceName, sha256.Sum256(source))
	ipv6Off := c.System.IPv6 == "off"

	files := Files{}
	add := func(path, name string, data any) error {
		var b bytes.Buffer
		if err := tmpl.ExecuteTemplate(&b, name, data); err != nil {
			return fmt.Errorf("rendering %s: %w", path, err)
		}
		files[path] = b.Bytes()
		return nil
	}

	vlansOn := map[string][]string{}
	for _, v := range c.VLANs {
		vlansOn[v.Parent] = append(vlansOn[v.Parent], v.Name)
	}

	// ipv6 = "auto" (ADR 0008).
	var ids map[string]int
	var wanDevice string
	if !ipv6Off {
		if !c.IPv6.ULA.IsValid() {
			return nil, fmt.Errorf("no local IPv6 prefix: set ipv6.ula_prefix, or let the caller supply one (see LocalPrefix)")
		}
		ids = subnetIDs(c)
		for _, in := range c.Interfaces {
			if in.Zone == "wan" {
				wanDevice = in.Device()
			}
		}
		for _, v := range c.VLANs {
			if v.Zone == "wan" {
				wanDevice = v.Name
			}
		}
		// Store the prefix, so a generated one stays the same from now on.
		if c.IPv6.ULAPrefix == "" {
			files[ULAStateFile] = []byte(header + "\n# The router's local IPv6 prefix (ADR 0008). Set ipv6.ula_prefix to change it.\n" + c.IPv6.ULA.String() + "\n")
		}
	}
	setIPv6 := func(n *network) {
		switch id, ok := ids[n.Name]; {
		case ipv6Off:
		case n.WAN:
			n.WANIPv6 = c.IPv6.WANPrefixHint
		case ok:
			p := subnet64(c.IPv6.ULA, id)
			n.IPv6 = &lanIPv6{
				Addr: routerAddr(p).String(), Prefix: p.String(), DNS: routerAddr(p).Addr().String(),
				SubnetID: fmt.Sprintf("0x%x", id), Domain: c.System.Domain, Uplink: wanDevice,
			}
		}
	}

	for _, in := range c.Interfaces {
		n := network{
			Header: header, Kind: "interface", Name: in.Name, Zone: in.Zone,
			Device: in.Device(), WAN: in.Zone == "wan", DHCPClient: in.IPv4 == "dhcp",
			VLANs: vlansOn[in.Name], IPv6Off: ipv6Off,
		}
		if in.Addr.IsValid() {
			n.Addr = in.Addr.String()
		}
		setIPv6(&n)
		if in.MatchMAC != "" {
			n.MAC = in.MatchMAC
			if err := add("etc/systemd/network/10-rollgate-"+in.Name+".link", "link.tmpl", n); err != nil {
				return nil, err
			}
		}
		if err := add("etc/systemd/network/30-rollgate-"+in.Name+".network", "network.tmpl", n); err != nil {
			return nil, err
		}
	}

	for _, v := range c.VLANs {
		n := network{
			Header: header, Kind: "VLAN", Name: v.Name, Zone: v.Zone, Device: v.Name,
			Parent: v.Parent, VLANID: v.ID, WAN: v.Zone == "wan", DHCPClient: v.IPv4 == "dhcp",
			IPv6Off: ipv6Off,
		}
		if v.Addr.IsValid() {
			n.Addr = v.Addr.String()
		}
		setIPv6(&n)
		if err := add("etc/systemd/network/20-rollgate-"+v.Name+".netdev", "netdev.tmpl", n); err != nil {
			return nil, err
		}
		if err := add("etc/systemd/network/30-rollgate-"+v.Name+".network", "network.tmpl", n); err != nil {
			return nil, err
		}
	}

	// The WireGuard VPN (ADR 0018): a device named like its zone, with the
	// router's address inside the VPN. IPv4 only for now.
	if v := c.VPN; v != nil {
		wg := struct {
			Header, Device, KeyFile string
			Port                    int
			Peers                   []config.Peer
		}{header, config.VPNZone, vpn.KeyFile, v.Port, v.Peers}
		if err := add("etc/systemd/network/20-rollgate-"+config.VPNZone+".netdev", "wireguard.tmpl", wg); err != nil {
			return nil, err
		}
		n := network{Header: header, Kind: "VPN", Name: config.VPNZone, Zone: config.VPNZone, Device: config.VPNZone, Addr: v.Addr.String()}
		if err := add("etc/systemd/network/30-rollgate-"+config.VPNZone+".network", "network.tmpl", n); err != nil {
			return nil, err
		}
	}

	sysctl := struct {
		Header  string
		IPv6Off bool
	}{header, ipv6Off}
	if err := add("etc/sysctl.d/90-rollgate.conf", "sysctl.tmpl", sysctl); err != nil {
		return nil, err
	}

	fw, err := buildFirewall(c, header)
	if err != nil {
		return nil, err
	}
	if err := add("etc/nftables.conf", "nftables.tmpl", fw); err != nil {
		return nil, err
	}
	if err := add("etc/dnsmasq.conf", "dnsmasq.tmpl", buildDNSMasq(c, header)); err != nil {
		return nil, err
	}
	if err := add("etc/unbound/unbound.conf", "unbound.tmpl", buildUnbound(c, header)); err != nil {
		return nil, err
	}
	// Same path as the M1 image's placeholder, which this file replaces.
	sshd := struct {
		Header string
		Keys   []string // secret names, validated to be plain file names
	}{header, c.Management.SSHAuthorizedKeys}
	if err := add("etc/ssh/sshd_config.d/10-rollgate.conf", "sshd.tmpl", sshd); err != nil {
		return nil, err
	}
	return files, nil
}

// Paths returns the file paths in sorted order.
func (f Files) Paths() []string {
	return slices.Sorted(maps.Keys(f))
}

// WriteTree writes the files below dir, which must not exist yet or be empty,
// so a compile never mixes with older output.
func (f Files) WriteTree(dir string) error {
	if entries, err := os.ReadDir(dir); err == nil && len(entries) > 0 {
		return fmt.Errorf("%s is not empty; choose a new directory", dir)
	}
	for _, p := range f.Paths() {
		target := filepath.Join(dir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(target, f[p], 0o644); err != nil {
			return err
		}
	}
	return nil
}
