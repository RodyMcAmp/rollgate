package compile

import (
	"bytes"
	"flag"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/RodyMcAmp/rollgate/compiler/config"
)

// Golden tests (docs/testing.md): each tests/golden/<case>/router.toml must
// compile to exactly the files in tests/golden/<case>/expected/.
// `make golden-update` rewrites expected/; review that diff in the PR.
var update = flag.Bool("update", false, "rewrite tests/golden/*/expected from the compiler's output")

const goldenDir = "../../tests/golden"

func TestGolden(t *testing.T) {
	cases, err := os.ReadDir(goldenDir)
	if err != nil || len(cases) == 0 {
		t.Fatalf("no golden cases in %s: %v", goldenDir, err)
	}
	for _, tc := range cases {
		if !tc.IsDir() {
			continue
		}
		t.Run(tc.Name(), func(t *testing.T) {
			dir := filepath.Join(goldenDir, tc.Name())
			source, err := os.ReadFile(filepath.Join(dir, "router.toml"))
			if err != nil {
				t.Fatal(err)
			}
			if tc.Name() == "example" {
				checkExampleCopy(t, dir, source)
			}
			c, err := config.Parse(source)
			if err != nil {
				t.Fatalf("router.toml is invalid:\n%v", err)
			}
			if !c.IPv6.ULA.IsValid() {
				c.IPv6.ULA = testULA // stands in for the stored or generated prefix
			}
			files, err := Compile(c, source, "router.toml")
			if err != nil {
				t.Fatal(err)
			}
			for _, p := range files.Paths() {
				if !bytes.HasPrefix(files[p], []byte("# Generated by rollgate compile from router.toml (sha256 ")) {
					t.Errorf("%s doesn't start with the generated-file header", p)
				}
			}

			expectedDir := filepath.Join(dir, "expected")
			if *update {
				if err := os.RemoveAll(expectedDir); err != nil {
					t.Fatal(err)
				}
				if err := files.WriteTree(expectedDir); err != nil {
					t.Fatal(err)
				}
				return
			}
			want := readTree(t, expectedDir)
			for _, p := range files.Paths() {
				if w, ok := want[p]; !ok {
					t.Errorf("compiler produced %s, which isn't in expected/", p)
				} else if !bytes.Equal(files[p], w) {
					t.Errorf("%s differs from expected/:\n--- got\n%s\n--- want\n%s", p, files[p], w)
				}
			}
			for _, p := range slices.Sorted(maps.Keys(want)) {
				if _, ok := files[p]; !ok {
					t.Errorf("expected/%s wasn't produced", p)
				}
			}
			if t.Failed() {
				t.Log("If the change is intended, run `make golden-update` and review the diff.")
			}
		})
	}
}

// checkExampleCopy keeps the example golden case identical to
// examples/router.toml, so the documented example is always covered.
func checkExampleCopy(t *testing.T, dir string, source []byte) {
	example, err := os.ReadFile("../../examples/router.toml")
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(source, example) {
		return
	}
	if *update {
		if err := os.WriteFile(filepath.Join(dir, "router.toml"), example, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Fatal("copied examples/router.toml into the example case; run the update again")
	}
	t.Fatal("tests/golden/example/router.toml must be a copy of examples/router.toml; run `make golden-update`")
}

func readTree(t *testing.T, root string) map[string][]byte {
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		files[strings.ReplaceAll(rel, string(filepath.Separator), "/")] = data
		return nil
	})
	if err != nil {
		t.Fatalf("reading %s: %v (run `make golden-update` to create it)", root, err)
	}
	return files
}
