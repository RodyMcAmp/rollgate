#!/usr/bin/env bash
# Builds the rollgate disk image from the pinned Arch Linux Archive date.
#
# Usage:  sudo image/build.sh        (on an Arch Linux host, as root; see docs/dev-setup.md)
# Env:    BUILD_DIR      output directory (default: <repo>/build). Must be on a Linux
#                        filesystem, not /mnt/c under WSL.
#         DISK_SIZE_MIB  disk image size (default: 8192)
#         IMAGE_DATE     build at this Arch Linux Archive date instead of image/snapshot-date
#                        (make image-previous: the L4 test's "previous release")
#         ROLLGATE       the static rollgate binary to install (default: $BUILD_DIR/rollgate,
#                        built by make rollgate; make image builds it first)
#         RELEASE_KEY_FILE  the release signing key's public half (default:
#                        image/release-key.asc, once the maintainer has created it)
#
# Output: $BUILD_DIR/rollgate-<date>.img (raw GPT disk, UEFI) and a .sha256 file.
#
# How it works (ADR 0009): the ESP and the Btrfs root are built as separate filesystem
# image files on plain loop devices, filled with pacstrap, then copied into a GPT disk
# image at fixed offsets. No partitioned loop devices are needed, so this also runs in
# an unprivileged-udev container (CI).
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
image_dir="$repo_root/image"
build_dir=$(realpath -m "${BUILD_DIR:-$repo_root/build}")
disk_mib=${DISK_SIZE_MIB:-8192}
esp_mib=512
# Layout: 1 MiB (GPT + alignment) | ESP | root | 1 MiB (backup GPT)
root_mib=$((disk_mib - esp_mib - 2))
# Kept in sync with tests/vm/boot-test.sh, which reads the ESP at this offset.
esp_start_sector=2048
root_start_sector=$((esp_start_sector + esp_mib * 2048))

die() { echo "build: error: $*" >&2; exit 1; }
log() { echo "==> $*"; }

[[ $EUID -eq 0 ]] || die "must run as root"
for tool in pacstrap arch-chroot mkfs.btrfs mkfs.fat sgdisk losetup blkid btrfs; do
  command -v "$tool" >/dev/null || die "missing '$tool' (see docs/dev-setup.md)"
done
rollgate_bin=$(realpath -m "${ROLLGATE:-$build_dir/rollgate}")
[[ -x $rollgate_bin ]] || die "no rollgate binary at $rollgate_bin (run: make rollgate)"
((root_mib >= 4096)) || die "DISK_SIZE_MIB too small (need at least $((4096 + esp_mib + 2)))"

date=${IMAGE_DATE:-$(tr -d '[:space:]' < "$image_dir/snapshot-date")}
[[ $date =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || die "bad image/snapshot-date: '$date'"
# Literal $repo and $arch are expanded by pacman, not by the shell.
mirror="https://archive.archlinux.org/repos/${date//-//}/\$repo/os/\$arch"

work="$build_dir/work"
mnt="$work/mnt"
out="$build_dir/rollgate-$date.img"
loops=()

# Stop processes that still hold the target open, so it can be unmounted.
# pacstrap -K starts a gpg-agent for the target's keyring; without /run/user/0 (as in
# CI containers) its sockets live inside the target. Anything else is logged by name.
release_target() {
  gpgconf --homedir "$mnt/etc/pacman.d/gnupg" --kill all 2>/dev/null || true
  local proc link pid users=()
  for proc in /proc/[0-9]*; do
    for link in "$proc/root" "$proc/cwd" "$proc"/fd/*; do
      if [[ $(readlink "$link" 2>/dev/null) == "$mnt"/* ]]; then
        users+=("${proc#/proc/}")
        break
      fi
    done
  done
  ((${#users[@]})) || return 0
  for pid in "${users[@]}"; do
    log "stopping process $pid, still using the target: $(tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null)"
    kill "$pid" 2>/dev/null || true
  done
  for _ in 1 2 3 4 5; do
    kill -0 "${users[@]}" 2>/dev/null || return 0
    sleep 1
  done
  kill -9 "${users[@]}" 2>/dev/null || true
}

cleanup() {
  release_target
  umount -R "$mnt" 2>/dev/null || true
  for loop in "${loops[@]}"; do losetup -d "$loop" 2>/dev/null || true; done
}
trap cleanup EXIT

# A previous failed run may have left mounts behind; never rm -rf through a mount.
umount -R "$mnt" 2>/dev/null || true
rm -rf "$work"
mkdir -p "$mnt" "$build_dir/pkgcache"

mapfile -t packages < <(sed -e 's/#.*//' -e 's/[[:space:]]*$//' -e '/^$/d' "$image_dir/packages.txt")

log "snapshot date $date, ${#packages[@]} packages, ${disk_mib} MiB disk"

cat > "$work/pacman.conf" <<EOF
# Generated by image/build.sh: build-time pacman config pinned to $date.
[options]
Architecture = auto
CacheDir = $build_dir/pkgcache/
CheckSpace
ParallelDownloads = 5
SigLevel = Required DatabaseOptional
LocalFileSigLevel = Optional

[core]
Server = $mirror

[extra]
Server = $mirror
EOF

log "creating filesystems"
truncate -s "${esp_mib}M" "$work/esp.img"
truncate -s "${root_mib}M" "$work/root.img"
mkfs.fat -F 32 -n ESP "$work/esp.img" >/dev/null
mkfs.btrfs -q -L rollgate "$work/root.img"
esp_uuid=$(blkid -s UUID -o value "$work/esp.img")
root_uuid=$(blkid -s UUID -o value "$work/root.img")

root_loop=$(losetup --find --show "$work/root.img")
loops+=("$root_loop")
esp_loop=$(losetup --find --show "$work/esp.img")
loops+=("$esp_loop")

# Subvolume layout: docs/architecture.md#disk-layout
mount "$root_loop" "$mnt"
for subvol in @ @snapshots @var_log @rollgate_state; do
  btrfs subvolume create "$mnt/$subvol" >/dev/null
done
umount "$mnt"

btrfs_opts="noatime,compress=zstd:1"
mount -o "$btrfs_opts,subvol=/@" "$root_loop" "$mnt"
mkdir -p "$mnt/.snapshots" "$mnt/var/log" "$mnt/var/lib/rollgate" "$mnt/efi"
mount -o "$btrfs_opts,subvol=/@snapshots" "$root_loop" "$mnt/.snapshots"
mount -o "$btrfs_opts,subvol=/@var_log" "$root_loop" "$mnt/var/log"
mount -o "$btrfs_opts,subvol=/@rollgate_state" "$root_loop" "$mnt/var/lib/rollgate"
mount "$esp_loop" "$mnt/efi"
chmod 750 "$mnt/.snapshots"

log "installing packages"
# Read by the initramfs build that runs inside pacstrap; no package owns this file.
mkdir -p "$mnt/etc"
echo KEYMAP=us > "$mnt/etc/vconsole.conf"
# -K: fresh keyring in the target. -M: don't copy the host mirrorlist.
# -c: download into $build_dir/pkgcache (CacheDir above) instead of the image.
# SNAP_PAC_SKIP: snapper isn't configured yet, so snap-pac's hooks would only fail.
# archive.archlinux.org sometimes stalls or times out. pacman downloads everything
# before installing anything, so a failed download leaves nothing half-installed and
# a retry is safe.
for attempt in 1 2 3; do
  if SNAP_PAC_SKIP=y pacstrap -C "$work/pacman.conf" -K -M -c "$mnt" "${packages[@]}"; then
    break
  fi
  ((attempt < 3)) || die "pacstrap failed 3 times (see the errors above)"
  log "pacstrap failed (attempt $attempt of 3); retrying in 30 seconds"
  sleep 30
done

log "copying overlay files"
# Explicit modes, never the checkout's: a Windows or WSL checkout makes everything 0777.
# Directories 0755 (existing ones untouched), files 0644, scripts 0755.
while IFS= read -r dir; do
  [[ -d $mnt/$dir ]] || install -d -m 0755 "$mnt/$dir"
done < <(cd "$image_dir/rootfs" && find . -mindepth 1 -type d -printf '%P\n')
while IFS= read -r file; do
  case $file in
    usr/local/sbin/* | usr/local/lib/rollgate/*) mode=0755 ;;
    *) mode=0644 ;;
  esac
  install -m "$mode" "$image_dir/rootfs/$file" "$mnt/$file"
done < <(cd "$image_dir/rootfs" && find . -type f -printf '%P\n')
if [[ -f $image_dir/authorized_keys ]]; then
  install -D -m 0600 "$image_dir/authorized_keys" "$mnt/root/.ssh/authorized_keys"
  chmod 0700 "$mnt/root/.ssh"
fi

# rollgate itself is a pacman package (packaging/rollgate), built from $ROLLGATE and
# installed in the chroot below, so that releases can upgrade it from the [rollgate]
# repository (ADR 0012).
log "building the rollgate package"
rollgate_pkg=$(bash "$image_dir/../packaging/build.sh" "$date" "$rollgate_bin" "$work/pkg")
install -m 0644 "$rollgate_pkg" "$mnt/root/"

log "writing generated config"
cat > "$mnt/etc/fstab" <<EOF
# Generated by image/build.sh. No subvolid= on purpose: rollback replaces @ (ADR 0004).
UUID=$root_uuid  /                  btrfs  $btrfs_opts,subvol=/@               0 0
UUID=$root_uuid  /.snapshots        btrfs  $btrfs_opts,subvol=/@snapshots      0 0
UUID=$root_uuid  /var/log           btrfs  $btrfs_opts,subvol=/@var_log        0 0
UUID=$root_uuid  /var/lib/rollgate  btrfs  $btrfs_opts,subvol=/@rollgate_state 0 0
UUID=$esp_uuid   /efi               vfat   rw,umask=0077                       0 2
EOF

cat > "$mnt/etc/pacman.d/mirrorlist" <<EOF
# Generated by image/build.sh. Pinned to release $date (ADR 0002).
# rollgate update (M4) rewrites this; don't point it at live mirrors.
Server = $mirror
EOF

echo rollgate > "$mnt/etc/hostname"
echo LANG=C.UTF-8 > "$mnt/etc/locale.conf"
ln -sf /usr/share/zoneinfo/UTC "$mnt/etc/localtime"

# The release signing key (ADR 0012): rollgate update accepts releases.json only when
# it is signed by a key listed in release-keys, so a router can update only if its
# image carries the key. Until the maintainer creates it, updates stay off.
release_key=${RELEASE_KEY_FILE:-$image_dir/release-key.asc}
release_fpr=
if [[ -f $release_key ]]; then
  release_fpr=$(gpg --batch --with-colons --show-keys "$release_key" | awk -F: '$1 == "fpr" { print $10; exit }')
  [[ $release_fpr =~ ^[0-9A-F]{40}([0-9A-F]{24})?$ ]] || die "no key fingerprint in $release_key"
  log "trusting release key $release_fpr"
  install -m 0644 "$release_key" "$mnt/root/release-key.asc"
  echo "$release_fpr" >> "$mnt/usr/lib/rollgate/release-keys"
  # The [rollgate] repository, after core and extra, pinned to this release like the
  # archive; rollgate update moves it to the new date (docs/build-and-release.md).
  cat >> "$mnt/etc/pacman.conf" <<'EOF'

# rollgate's own packages (ADR 0012), signed by the release key.
[rollgate]
SigLevel = Required
Include = /etc/pacman.d/rollgate-mirrorlist
EOF
  cat > "$mnt/etc/pacman.d/rollgate-mirrorlist" <<EOF
# Generated by image/build.sh. The [rollgate] repository at release $date (ADR 0012).
# rollgate update rewrites this.
Server = https://rodymcamp.github.io/rollgate/repo/$date/\$arch
EOF
else
  log "no release key ($release_key): rollgate update will refuse to run on this image"
fi

log "configuring system in chroot"
# Run from a file, not stdin, so no command inside can swallow the rest of the script.
cat > "$mnt/root/configure.sh" <<'CHROOT'
# The release key goes into pacman's keyring, which rollgate update checks
# releases.json against, and is signed locally so pacman also trusts it for the
# [rollgate] repository.
if [[ -f /root/release-key.asc ]]; then
  pacman-key --add /root/release-key.asc >/dev/null
  pacman-key --lsign-key "$(tail -n 1 /usr/lib/rollgate/release-keys)" >/dev/null
  rm /root/release-key.asc
fi

# rollgate itself, from the package build.sh made (a local file: no repository needed).
pacman -U --noconfirm --noprogressbar /root/rollgate-*.pkg.tar.zst >/dev/null
rm /root/rollgate-*.pkg.tar.zst

# snapper: root config pointing at the separate @snapshots subvolume. Written by hand
# because `snapper create-config` insists on creating /.snapshots as a nested subvolume.
install -m 0644 /usr/share/snapper/config-templates/default /etc/snapper/configs/root
sed -i \
  -e 's/^TIMELINE_CREATE=.*/TIMELINE_CREATE="no"/' \
  -e 's/^NUMBER_LIMIT=.*/NUMBER_LIMIT="10"/' \
  -e 's/^NUMBER_LIMIT_IMPORTANT=.*/NUMBER_LIMIT_IMPORTANT="5"/' \
  /etc/snapper/configs/root
sed -i 's/^SNAPPER_CONFIGS=.*/SNAPPER_CONFIGS="root"/' /etc/conf.d/snapper

# grub-btrfs must find grub.cfg on the ESP (ADR 0009). The config file is sourced as
# shell, so a line appended at the end wins.
echo 'GRUB_BTRFS_GRUB_DIRNAME="/efi/grub"' >> /etc/default/grub-btrfs/config

mkinitcpio -P

# GRUB's own files (modules, grub.cfg, grubenv) go on the ESP; kernels stay in /boot on
# Btrfs. --removable: EFI/BOOT/BOOTX64.EFI, so the image boots without NVRAM entries.
grub-install --target=x86_64-efi --efi-directory=/efi --boot-directory=/efi \
  --removable --no-nvram
# grub-install saw an unpartitioned ESP image and embedded the prefix "()/grub", which
# makes GRUB look at the whole disk on real hardware. Rebuild the EFI binary with an
# early config that finds the ESP by filesystem UUID instead (written by build.sh).
grub-mkimage -O x86_64-efi -p /grub -c /root/grub-early.cfg \
  -o /efi/EFI/BOOT/BOOTX64.EFI \
  part_gpt fat search search_fs_uuid configfile normal
[[ -f /efi/grub/grubenv ]] || grub-editenv /efi/grub/grubenv create
grub-mkconfig -o /efi/grub/grub.cfg

systemctl enable systemd-networkd.service systemd-resolved.service sshd.service \
  nftables.service grub-btrfsd.service snapper-cleanup.timer \
  rollgate-boot-report.service rollgate-boot.service rollgate-health.service \
  rollgate-softdog.service
# The CLI runs on the target (a static binary needs nothing from it).
rollgate help >/dev/null
# Nothing in M1 needs network-online, and unplugged ports would make it time out.
systemctl disable systemd-networkd-wait-online.service
# The image is preconfigured; firstboot would block boot waiting for console input.
systemctl mask systemd-firstboot.service

# Console login: no root password until the owner sets one (/etc/issue says so), as on
# OpenWrt. SSH never accepts it (key-only). Don't expire it instead: an expired password
# makes sshd refuse key logins too ("Password change required but no TTY available").
passwd -d root >/dev/null
CHROOT
cat > "$mnt/root/grub-early.cfg" <<EOF
search --no-floppy --fs-uuid --set=root $esp_uuid
set prefix=(\$root)/grub
EOF
arch-chroot "$mnt" /bin/bash -euo pipefail /root/configure.sh
rm "$mnt/root/configure.sh" "$mnt/root/grub-early.cfg"

# arch-chroot bind-mounts the host's resolv.conf, so link it after leaving the chroot.
ln -sf ../run/systemd/resolve/stub-resolv.conf "$mnt/etc/resolv.conf"
# Empty machine-id: each installed router generates its own on first boot.
: > "$mnt/etc/machine-id"

log "checking the result"
grub_cfg="$mnt/efi/grub/grub.cfg"
grep -q "vmlinuz-linux-lts" "$grub_cfg" || die "grub.cfg has no linux-lts entry"
grep -q "root=UUID=$root_uuid" "$grub_cfg" || die "grub.cfg does not boot root UUID $root_uuid"
grep -q "rootflags=subvol=@" "$grub_cfg" || die "grub.cfg does not set rootflags=subvol=@"
grep -q "custom.cfg" "$grub_cfg" || die "grub.cfg does not read custom.cfg (rollgate update's trial entry, ADR 0011)"
! grep -q "BootNext" "$grub_cfg" || die "grub.cfg lists the build machine's firmware boot entries"
[[ -f $mnt/efi/EFI/BOOT/BOOTX64.EFI ]] || die "GRUB EFI binary missing from the ESP"
grep -qa "$esp_uuid" "$mnt/efi/EFI/BOOT/BOOTX64.EFI" || die "GRUB EFI binary does not search for ESP UUID $esp_uuid"
[[ -f $mnt/boot/vmlinuz-linux && -f $mnt/boot/vmlinuz-linux-lts ]] || die "kernels missing from /boot"
[[ -L $mnt/etc/systemd/system/sysinit.target.wants/rollgate-boot.service ]] || die "rollgate-boot.service not enabled"
[[ -L $mnt/etc/systemd/system/sysinit.target.wants/rollgate-softdog.service ]] || die "rollgate-softdog.service not enabled"
grep -qx "RuntimeWatchdogSec=30s" "$mnt/etc/systemd/system.conf.d/10-rollgate-watchdog.conf" || die "systemd watchdog not configured"
[[ -d $mnt/var/lib/pacman/local/rollgate-${date//-/.}-1 ]] || die "the rollgate package isn't installed"
[[ -x $mnt/usr/bin/rollgate && -f $mnt/usr/lib/systemd/system/rollgate-health.service ]] || die "the rollgate package's files are missing"
if [[ -n $release_fpr ]]; then
  grep -qx "$release_fpr" "$mnt/usr/lib/rollgate/release-keys" || die "release key not listed in release-keys"
  gpg --homedir "$mnt/etc/pacman.d/gnupg" --batch --with-colons --list-keys "$release_fpr" 2>/dev/null |
    grep -q '^pub:f:' || die "release key $release_fpr is not in pacman's keyring with full trust"
  gpgconf --homedir "$mnt/etc/pacman.d/gnupg" --kill all 2>/dev/null || true
fi
# World-writable files or non-sticky directories (sticky ones like /tmp are fine).
world_writable=$(find "$mnt" \( -type f -o -type d \) -perm -0002 ! -perm -1000 -print -quit)
[[ -z $world_writable ]] || die "world-writable path in image: ${world_writable#"$mnt"}"

release_target
umount -R "$mnt"

log "assembling disk image"
rm -f "$out" "$out.sha256"
truncate -s "${disk_mib}M" "$out"
sgdisk --clear \
  --new=1:${esp_start_sector}:+${esp_mib}M --typecode=1:ef00 --change-name=1:ESP \
  --new=2:${root_start_sector}:+${root_mib}M --typecode=2:8304 --change-name=2:rollgate-root \
  "$out" >/dev/null
dd if="$work/esp.img" of="$out" bs=512 seek="$esp_start_sector" conv=notrunc,sparse status=none
dd if="$work/root.img" of="$out" bs=512 seek="$root_start_sector" conv=notrunc,sparse status=none
sync

cleanup
trap - EXIT
rm -rf "$work"
(cd "$build_dir" && sha256sum "$(basename "$out")" > "$(basename "$out").sha256")

log "done: $out"
