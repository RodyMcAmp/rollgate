#!/usr/bin/env bash
# Builds the rollgate USB installer image (ADR 0021) from the router image and the
# pinned Arch Linux Archive date.
#
# Usage:  sudo image/installer.sh        (make installer; on an Arch Linux host, as root)
# Env:    BUILD_DIR     output directory (default: <repo>/build), on a Linux filesystem
#         IMAGE_DATE    build at this archive date instead of image/snapshot-date
#         ROLLGATE      the static rollgate binary (default: $BUILD_DIR/rollgate)
#         ROUTER_IMAGE  the router image to install (default: $BUILD_DIR/rollgate-<date>.img,
#                       made by make image), with its .sha256 file next to it
#
# Output: $BUILD_DIR/rollgate-installer-<date>.img and a .sha256 file. It's written to
# a USB stick as it is (balenaEtcher, Rufus in DD mode, or dd).
#
# Layout: an MBR partition table, so Windows and macOS show the first partition (they
# hide a GPT EFI system partition), and UEFI firmware boots it as removable media:
#   1 MiB | FAT32 "ROLLGATE", 256 MiB, type 0x0c: GRUB (EFI/BOOT/BOOTX64.EFI), the
#         |   kernel and initramfs, and the rollgate/ folder with README.txt
#         | squashfs, type 0x83: the installer's own system (read-only; a layer in
#         |   memory on top) with the zstd-compressed router image
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
image_dir="$repo_root/image"
build_dir=$(realpath -m "${BUILD_DIR:-$repo_root/build}")
esp_mib=256
esp_start=2048

die() { echo "installer: error: $*" >&2; exit 1; }
log() { echo "==> $*"; }

[[ $EUID -eq 0 ]] || die "must run as root"
for tool in pacstrap arch-chroot mkfs.fat mksquashfs sfdisk zstd blkid losetup sha256sum; do
  command -v "$tool" >/dev/null || die "missing '$tool' (see docs/dev-setup.md)"
done
rollgate_bin=$(realpath -m "${ROLLGATE:-$build_dir/rollgate}")
[[ -x $rollgate_bin ]] || die "no rollgate binary at $rollgate_bin (run: make rollgate)"

date=${IMAGE_DATE:-$(tr -d '[:space:]' < "$image_dir/snapshot-date")}
[[ $date =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}$ ]] || die "bad image/snapshot-date: '$date'"
mirror="https://archive.archlinux.org/repos/${date//-//}/\$repo/os/\$arch"
router_image=$(realpath -m "${ROUTER_IMAGE:-$build_dir/rollgate-$date.img}")
[[ $(basename "$router_image") == "rollgate-$date.img" ]] || die "$router_image: expected rollgate-$date.img"
[[ -f $router_image && -f $router_image.sha256 ]] || die "no router image at $router_image (run: make image)"
log "checking $router_image"
(cd "$(dirname "$router_image")" && sha256sum --quiet -c "$(basename "$router_image").sha256") ||
  die "$router_image doesn't match its .sha256 file"

work="$build_dir/installer-work"
root="$work/root"
out="$build_dir/rollgate-installer-$date.img"
loops=()

# As in image/build.sh: stop processes that still use the target (pacstrap's
# gpg-agent above all), so it can be unmounted.
release_target() {
  gpgconf --homedir "$root/etc/pacman.d/gnupg" --kill all 2>/dev/null || true
  local proc link pid users=()
  for proc in /proc/[0-9]*; do
    for link in "$proc/root" "$proc/cwd" "$proc"/fd/*; do
      if [[ $(readlink "$link" 2>/dev/null) == "$root"/* ]]; then
        users+=("${proc#/proc/}")
        break
      fi
    done
  done
  ((${#users[@]})) || return 0
  for pid in "${users[@]}"; do
    log "stopping process $pid, still using the target: $(tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null)"
    kill "$pid" 2>/dev/null || true
  done
  sleep 2
  kill -9 "${users[@]}" 2>/dev/null || true
}

cleanup() {
  release_target
  umount -R "$root" 2>/dev/null || true
  for loop in "${loops[@]}"; do losetup -d "$loop" 2>/dev/null || true; done
}
trap cleanup EXIT

umount -R "$root" 2>/dev/null || true
rm -rf "$work"
mkdir -p "$root" "$build_dir/pkgcache"
# pacstrap and arch-chroot want a mount point.
mount --bind "$root" "$root"

mapfile -t packages < <(sed -e 's/#.*//' -e 's/[[:space:]]*$//' -e '/^$/d' "$image_dir/installer/packages.txt")
log "snapshot date $date, ${#packages[@]} packages"

cat > "$work/pacman.conf" <<EOF
# Generated by image/installer.sh: build-time pacman config pinned to $date.
[options]
Architecture = auto
CacheDir = $build_dir/pkgcache/
CheckSpace
ParallelDownloads = 5
SigLevel = Required DatabaseOptional
LocalFileSigLevel = Optional

[core]
Server = $mirror

[extra]
Server = $mirror
EOF

# The MBR's disk signature makes the partitions' PARTUUIDs (<signature>-01, -02),
# which the boot loader and fstab use to find them on this stick.
label_id=$(od -An -N4 -tx4 /dev/urandom | tr -d ' \n')
[[ $label_id =~ ^[0-9a-f]{8}$ && $label_id != 00000000 ]] || die "couldn't make a disk signature"
esp_partuuid="$label_id-01"
system_partuuid="$label_id-02"

log "creating the FAT partition"
truncate -s "${esp_mib}M" "$work/esp.img"
mkfs.fat -F 32 -n ROLLGATE "$work/esp.img" >/dev/null
esp_uuid=$(blkid -s UUID -o value "$work/esp.img")
esp_loop=$(losetup --find --show "$work/esp.img")
loops+=("$esp_loop")

log "installing packages"
mkdir -p "$root/etc"
echo KEYMAP=us > "$root/etc/vconsole.conf"
for attempt in 1 2 3; do
  if pacstrap -C "$work/pacman.conf" -K -M -c "$root" "${packages[@]}"; then
    break
  fi
  ((attempt < 3)) || die "pacstrap failed 3 times (see the errors above)"
  log "pacstrap failed (attempt $attempt of 3); retrying in 30 seconds"
  sleep 30
done

log "copying overlay files and rollgate"
while IFS= read -r dir; do
  [[ -d $root/$dir ]] || install -d -m 0755 "$root/$dir"
done < <(cd "$image_dir/installer/rootfs" && find . -mindepth 1 -type d -printf '%P\n')
while IFS= read -r file; do
  install -m 0644 "$image_dir/installer/rootfs/$file" "$root/$file"
done < <(cd "$image_dir/installer/rootfs" && find . -type f -printf '%P\n')
install -m 0755 "$rollgate_bin" "$root/usr/bin/rollgate"

cat > "$root/etc/fstab" <<EOF
# Generated by image/installer.sh. The root file system is the stick's squashfs with
# a layer in memory on top (rollgate-overlay in the initramfs). This is the stick's
# FAT partition, where rollgate install reads ssh-key.pub and router.toml and writes
# install-log.txt and hardware.txt (ADR 0021).
PARTUUID=$esp_partuuid  /run/rollgate/stick  vfat  rw,noatime,flush,umask=0022,nofail,x-systemd.device-timeout=30s  0 0
EOF
echo rollgate-installer > "$root/etc/hostname"
echo LANG=C.UTF-8 > "$root/etc/locale.conf"
ln -sf /usr/share/zoneinfo/UTC "$root/etc/localtime"

log "compressing the router image"
install -d -m 0755 "$root/usr/share/rollgate"
zstd -q -T0 -10 "$router_image" -o "$root/usr/share/rollgate/rollgate-$date.img.zst"
install -m 0644 "$router_image.sha256" "$root/usr/share/rollgate/rollgate-$date.img.sha256"

log "configuring the system and the boot loader in chroot"
mkdir -p "$root/efi"
mount "$esp_loop" "$root/efi"
cat > "$root/root/grub-early.cfg" <<EOF
search --no-floppy --fs-uuid --set=root $esp_uuid
set prefix=(\$root)/grub
EOF
cat > "$root/root/configure.sh" <<'CHROOT'
mkinitcpio -p linux-lts
lsinitcpio /boot/initramfs-linux-lts.img | grep -qx 'hooks/rollgate-overlay' ||
  { echo "the initramfs lacks the rollgate-overlay hook" >&2; exit 1; }

# GRUB, built with an early config that finds this stick's FAT partition by its
# UUID; its modules next to grub.cfg. --removable path: no firmware entry needed.
install -d /efi/EFI/BOOT /efi/grub /efi/boot /efi/rollgate
grub-mkimage -O x86_64-efi -p /grub -c /root/grub-early.cfg -o /efi/EFI/BOOT/BOOTX64.EFI \
  part_msdos part_gpt fat search search_fs_uuid configfile normal
cp -r /usr/lib/grub/x86_64-efi /efi/grub/
cp /boot/vmlinuz-linux-lts /boot/initramfs-linux-lts.img /efi/boot/
rm -f /boot/initramfs-*.img /boot/vmlinuz-*

systemctl enable rollgate-installer.service
# rollgate install reads the screen and the serial console itself.
systemctl mask getty@tty1.service serial-getty@ttyS0.service systemd-firstboot.service
systemctl set-default multi-user.target
# No password for root on the installer: there's no network service to log in to,
# and tty2's login prompt (Alt+F2) is for looking around while it runs.
passwd -d root >/dev/null
rollgate help >/dev/null
CHROOT
arch-chroot "$root" /bin/bash -euo pipefail /root/configure.sh
rm "$root/root/configure.sh" "$root/root/grub-early.cfg"

cat > "$root/efi/grub/grub.cfg" <<EOF
# Generated by image/installer.sh: the rollgate installer, release $date (ADR 0021).
serial --unit=0 --speed=115200
terminal_input console serial
terminal_output console serial
set timeout=3
set default=0
menuentry "Install rollgate $date" {
  linux /boot/vmlinuz-linux-lts root=PARTUUID=$system_partuuid rootfstype=squashfs ro rootdelay=30 console=tty0 console=ttyS0,115200 quiet loglevel=3
  initrd /boot/initramfs-linux-lts.img
}
EOF
sed 's/$/\r/' "$image_dir/installer/README.txt" > "$root/efi/rollgate/README.txt"
: > "$root/etc/machine-id"

log "checking the result"
[[ -f $root/efi/EFI/BOOT/BOOTX64.EFI ]] || die "GRUB EFI binary missing"
grep -qa "$esp_uuid" "$root/efi/EFI/BOOT/BOOTX64.EFI" || die "GRUB doesn't search for the FAT partition $esp_uuid"
[[ -f $root/efi/boot/vmlinuz-linux-lts && -f $root/efi/boot/initramfs-linux-lts.img ]] || die "kernel or initramfs missing"
[[ -L $root/etc/systemd/system/multi-user.target.wants/rollgate-installer.service ]] || die "rollgate-installer.service not enabled"
[[ $(readlink "$root/etc/systemd/system/getty@tty1.service") == /dev/null ]] || die "getty@tty1 isn't masked"
"$root/usr/bin/rollgate" help | grep -q 'install \[-console\]' || die "this rollgate has no install command"
[[ -f $root/usr/share/rollgate/rollgate-$date.img.zst ]] || die "the router image is missing"
world_writable=$(find "$root" -xdev \( -type f -o -type d \) -perm -0002 ! -perm -1000 -print -quit)
[[ -z $world_writable ]] || die "world-writable path: ${world_writable#"$root"}"

release_target
umount "$root/efi"
rmdir "$root/efi"
umount "$root"

log "making the squashfs"
mksquashfs "$root" "$work/system.sqfs" -comp zstd -noappend -quiet -no-progress

log "assembling the stick image"
system_mib=$(( ($(stat -c %s "$work/system.sqfs") + (1 << 20) - 1) >> 20 ))
system_start=$((esp_start + esp_mib * 2048))
rm -f "$out" "$out.sha256"
truncate -s "$((1 + esp_mib + system_mib))M" "$out"
sfdisk --quiet "$out" <<EOF
label: dos
label-id: 0x$label_id
unit: sectors
start=$esp_start, size=$((esp_mib * 2048)), type=c, bootable
start=$system_start, size=$((system_mib * 2048)), type=83
EOF
dd if="$work/esp.img" of="$out" bs=512 seek="$esp_start" conv=notrunc,sparse status=none
dd if="$work/system.sqfs" of="$out" bs=512 seek="$system_start" conv=notrunc,sparse status=none
sync
sfdisk --dump "$out" | grep -q "label-id: 0x$label_id" || die "the partition table wasn't written"

cleanup
trap - EXIT
rm -rf "$work"
(cd "$build_dir" && sha256sum "$(basename "$out")" > "$(basename "$out").sha256")
log "done: $out ($(du -h --apparent-size "$out" | cut -f1))"
